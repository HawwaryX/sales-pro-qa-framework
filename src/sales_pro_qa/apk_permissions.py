def describe_permission(name: str) -> tuple[str, str]:
    if name.startswith("android.permission."):
        return PERMISSIONS.get(name.removeprefix("android.permission."), (
            "صلاحية Android غير موصوفة في القاموس المحلي",
            "راجع وثائق Android الرسمية؛ لا يمكن استنتاج درجة الخطر أو سلوك الاستخدام."))
    return ("صلاحية خاصة بالتطبيق أو بمكتبة",
            "راجع تعريفها ومستوى الحماية والجهة المستقبلة؛ الاسم وحده لا يحدد دلالتها أو خطورتها.")
